-- Create profile automatically after signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles(id, full_name, email)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(coalesce(new.email,''),'@',1)),
    new.email
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

-- Borrowing transaction with inventory protection.
create or replace function public.borrow_book(p_book_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  update public.books
  set available_copies = available_copies - 1,
      updated_at = now()
  where id = p_book_id and available_copies > 0;

  if not found then
    raise exception 'Book is not available';
  end if;

  insert into public.borrowings(user_id, book_id)
  values (auth.uid(), p_book_id)
  returning id into new_id;

  insert into public.activities(user_id, book_id, activity_type)
  values (auth.uid(), p_book_id, 'borrow');

  return jsonb_build_object('id', new_id);
end;
$$;

create or replace function public.return_book(p_borrowing_id bigint)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_book_id bigint;
begin
  update public.borrowings
  set returned_at = now(), status = 'returned'
  where id = p_borrowing_id
    and user_id = auth.uid()
    and returned_at is null
  returning book_id into v_book_id;

  if not found then
    raise exception 'Borrowing record not found';
  end if;

  update public.books
  set available_copies = least(total_copies, available_copies + 1),
      updated_at = now()
  where id = v_book_id;

  insert into public.activities(user_id, book_id, activity_type)
  values (auth.uid(), v_book_id, 'return');

  return true;
end;
$$;

-- Lightweight hybrid recommendation RPC.
-- Content signal: matching category/author/keywords with the user's previous books.
-- Collaborative signal: books borrowed by users who also borrowed the current user's books.
create or replace function public.get_recommendations(p_limit integer default 8)
returns table (
  id bigint,
  title text,
  author text,
  category text,
  description text,
  cover_url text,
  score numeric
)
language sql
stable
security definer
set search_path = public
as $$
with my_books as (
  select distinct b.id, b.category_id, lower(coalesce(b.author,'')) author, lower(coalesce(b.keywords,'')) keywords
  from public.borrowings br
  join public.books b on b.id = br.book_id
  where br.user_id = auth.uid()
),
similar_users as (
  select distinct br2.user_id
  from public.borrowings br1
  join public.borrowings br2 on br1.book_id = br2.book_id
  where br1.user_id = auth.uid()
    and br2.user_id <> auth.uid()
),
candidates as (
  select
    b.*,
    (
      case when exists(select 1 from my_books m where m.category_id = b.category_id) then 3 else 0 end +
      case when exists(select 1 from my_books m where m.author <> '' and lower(b.author) = m.author) then 2 else 0 end +
      case when exists(
        select 1 from my_books m
        where m.keywords <> '' and lower(coalesce(b.keywords,'')) like '%' || split_part(m.keywords, ',', 1) || '%'
      ) then 1 else 0 end +
      case when exists(
        select 1 from public.borrowings br
        where br.user_id in (select user_id from similar_users)
          and br.book_id = b.id
      ) then 2 else 0 end
    )::numeric as score
  from public.books b
  where not exists (
    select 1 from public.borrowings br where br.user_id = auth.uid() and br.book_id = b.id and br.returned_at is null
  )
)
select c.id, c.title, c.author, cat.name, c.description, c.cover_url, c.score
from candidates c
left join public.categories cat on cat.id = c.category_id
order by c.score desc, c.created_at desc
limit greatest(1, least(p_limit, 50));
$$;

