create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text,
  role text not null default 'member' check (role in ('member','admin')),
  avatar_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  isbn text,
  category_id bigint references public.categories(id) on delete set null,
  description text,
  keywords text,
  cover_url text,
  published_year integer,
  total_copies integer not null default 1 check (total_copies >= 0),
  available_copies integer not null default 1 check (available_copies >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.borrowings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  borrowed_at timestamptz not null default now(),
  due_at timestamptz not null default (now() + interval '14 days'),
  returned_at timestamptz,
  status text not null default 'borrowed' check (status in ('borrowed','returned','overdue')),
  created_at timestamptz not null default now()
);

create table if not exists public.favourites (
  user_id uuid not null references public.profiles(id) on delete cascade,
  book_id bigint not null references public.books(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, book_id)
);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  book_id bigint references public.books(id) on delete cascade,
  activity_type text not null check (activity_type in ('view','search','borrow','return','favourite')),
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  title text not null,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists idx_books_category on public.books(category_id);
create index if not exists idx_books_title on public.books using gin (to_tsvector('english', coalesce(title,'') || ' ' || coalesce(author,'') || ' ' || coalesce(description,'') || ' ' || coalesce(keywords,'')));
create index if not exists idx_borrowings_user on public.borrowings(user_id);
create index if not exists idx_borrowings_book on public.borrowings(book_id);
create index if not exists idx_activities_user on public.activities(user_id);

